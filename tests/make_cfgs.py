#!/usr/bin/env python3
"""Writes the small test configs (tests/cfg/*.txt) and the T6 error cases
(tests/cfg/err/*.txt + expected message in tests/cfg/err/EXPECT).
Run once; the files are committed. Pure text, no numbers from holographer."""
import pathlib

D = pathlib.Path(__file__).resolve().parent / "cfg"
E = D / "err"
E.mkdir(parents=True, exist_ok=True)

# output_scale 1.0, chain gain 1 -> max_vrms 0.5 = -6.02 dBFS threshold
BASE = '''    output_scale: 1.0;
    chain: "c" { dac_max_output_vrms: 1.0; { gain_db: 0.0; }; };
    group: { channels: "subl", "subr"; chain: "c";
        limit: { name: "sub_peak"; max_vrms: 0.5; type: "peak"; attack_ms: 0.3; release_ms: 200.0; }; };
    group: { channels: "esll", "eslr"; chain: "c";
        limit: { name: "esl_peak"; max_vrms: 0.5; type: "peak"; attack_ms: 0.3; release_ms: 200.0; }; };
    group: { channels: "alkoven"; chain: "c";
        limit: { name: "alk_peak"; max_vrms: 0.5; type: "peak"; attack_ms: 0.3; release_ms: 200.0; }; };
'''
NO_ALK_GROUP = BASE.split('    group: { channels: "alkoven"')[0]


def link(name, ch, drive=None, ratio=None, offset=None, extra=""):
    s = f'    link: "{name}" {{\n        channels: ' + ", ".join(f'"{c}"' for c in ch) + ";\n"
    if drive is not None:
        s += "        drive: " + ", ".join(f'"{c}"' for c in drive) + ";\n"
    if ratio is not None:
        s += "        ratio: " + ", ".join(str(r) for r in ratio) + ";\n"
    if offset is not None:
        s += "        offset_db: " + ", ".join(str(o) for o in offset) + ";\n"
    return s + extra + "    };\n"


def w(name, text):
    (D / name).write_bytes(("# generated by make_cfgs.py\n" + text).encode())


w("simple_nolink.txt", BASE)
w("t2.txt", BASE + link("alk_fill", ["esll", "alkoven"], drive=["esll"], ratio=[1.0, 1.0]))
w("t5.txt", BASE + link("alk_fill", ["esll", "alkoven"], drive=["esll"], ratio=[1.0, 0.5]))
w("t4_o0.txt", BASE + link("esl_stereo", ["esll", "eslr"], offset=[0.0, 0.0]))
w("t4_o2.txt", BASE + link("esl_stereo", ["esll", "eslr"], offset=[2.0, 2.0]))
# positive syntax cases
w("ok_link_before_group.txt", '    output_scale: 1.0;\n    chain: "c" { dac_max_output_vrms: 1.0; { gain_db: 0.0; }; };\n'
  + link("x", ["esll", "alkoven"]) + BASE.split("\n", 2)[2])
w("ok_disabled.txt", BASE + link("x", ["esll", "alkoven"], extra="        enabled: 0;\n"))
w("ok_design_D.txt", BASE + link("all_main", ["esll", "eslr", "alkoven", "subl", "subr"],
                                 drive=["esll", "eslr"], ratio=[1.0] * 5))

errors = {
    "dup_link_name": (BASE + link("a", ["esll", "alkoven"]) + link("a", ["subl", "subr"]), "link name 'a' used twice"),
    "one_member": (BASE + link("a", ["esll"]), "at least 2 members"),
    "too_many_members": (BASE + link("a", ["esll", "eslr", "subl", "subr", "alkoven", "x1", "x2", "x3", "x4"]), "too many entries (max 8)"),
    "too_many_links": (BASE + "".join(link(f"l{i}", ["esll", "alkoven"]) for i in range(5)), "too many links (max 4)"),
    "unknown_output": (BASE + link("a", ["esl_l", "alkoven"]), "'esl_l' is not a BruteFIR output channel"),
    "member_no_group": (NO_ALK_GROUP + link("a", ["esll", "alkoven"]), "'alkoven' is in no protect group"),
    "chan_two_groups": (BASE + '    group: { channels: "esll"; chain: "c";\n        limit: { name: "x"; max_vrms: 0.4; type: "peak"; }; };\n',
                        "'esll' is in more than one group"),
    "chan_two_groups_same": (BASE.replace('channels: "subl", "subr"', 'channels: "subl", "subl"'), "'subl' is in more than one group"),
    "chan_two_links": (BASE + link("a", ["esll", "alkoven"]) + link("b", ["esll", "eslr"]), "'esll' is in more than one link"),
    "dup_member": (BASE + link("a", ["esll", "alkoven", "esll"]), "'esll' listed twice"),
    "drive_not_member": (BASE + link("a", ["esll", "alkoven"], drive=["eslr"]), "drive 'eslr' is not a member"),
    "drive_dup": (BASE + link("a", ["esll", "alkoven"], drive=["esll", "esll"]), "drive 'esll' listed twice"),
    "ratio_len": (BASE + link("a", ["esll", "alkoven"], ratio=[1.0]), "ratio has 1 entries, channels has 2"),
    "offset_len": (BASE + link("a", ["esll", "alkoven"], offset=[0.0, 0.0, 0.0]), "offset_db has 3 entries, channels has 2"),
    "ratio_high": (BASE + link("a", ["esll", "alkoven"], ratio=[1.0, 1.5]), "ratio 1.5 for 'alkoven' out of range"),
    "ratio_neg": (BASE + link("a", ["esll", "alkoven"], ratio=[-0.1, 1.0]), "ratio -0.1 for 'esll' out of range"),
    "offset_high": (BASE + link("a", ["esll", "alkoven"], offset=[0.0, 41.0]), "offset_db 41 for 'alkoven' out"),
    "offset_neg": (BASE + link("a", ["esll", "alkoven"], offset=[-1.0, 0.0]), "offset_db -1 for 'esll' out"),
    "unknown_field": (BASE + link("a", ["esll", "alkoven"], extra="        gain: 1.0;\n"), "unknown field 'gain'"),
    "field_twice": (BASE + link("a", ["esll", "alkoven"], extra='        channels: "subl", "subr";\n'), "field 'channels' given twice"),
    "empty_name": (BASE + link("", ["esll", "alkoven"]), "empty or too long link name"),
    "no_channels": (BASE + '    link: "a" { drive: "esll"; };\n', "at least 2 members (got 0)"),
    "ratio_not_number": (BASE + '    link: "a" { channels: "esll", "alkoven"; ratio: "x", "y"; };\n', "ratio: expected number"),
}
expect = []
for name, (text, msg) in errors.items():
    (E / f"{name}.txt").write_bytes(("# generated by make_cfgs.py - must be REJECTED\n" + text).encode())
    expect.append(f"{name}\t{msg}")
(E / "EXPECT").write_bytes(("\n".join(expect) + "\n").encode())
print(f"{len(list(D.glob('*.txt')))} configs, {len(errors)} error cases")
